def original_text(step: Step) -> str:
    """토큰을 원문의 대괄호 표기로 되돌린 원문 그대로의 프롬프트"""
    t = step.template.replace("{PREV_REF}", "[이전 결과 붙여 넣기]").replace("{PREV}", "[이전 결과 붙여 넣기]")
    for i in range(len(step.ctx_labels)):
        t = t.replace("{C%d}" % i, "[직접 적기]")
    return t


def build_prompt(step: Step, ctx_values: list, prev_result: str, use_boost: bool, extra_context: str = "") -> str:
    """사용자 입력으로 칸을 채운 최종 프롬프트"""
    t = step.template
    t = t.replace("{PREV_REF}", "아래 맥락의 이전 결과")
    t = t.replace("{PREV}", "\n<이전 결과>\n" + (prev_result.strip() or "(없음)") + "\n</이전 결과>")
    for i, v in enumerate(ctx_values):
        t = t.replace("{C%d}" % i, v.strip() or "(아직 적지 않음)")
    if extra_context.strip():
        t = t.replace("# 출력 형식:", "# 추가 맥락:\n" + extra_context.strip() + "\n\n# 출력 형식:", 1)
    if use_boost and step.boost:
        t += "\n\n" + step.boost
    return t


def fields_for(step: Step, use_boost: bool) -> list:
    return step.output_fields + (step.boost_fields if use_boost else [])


